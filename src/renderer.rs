use std::{fs::File, io::{BufWriter, Cursor, Write}};

use anyhow::{Context, Result, bail};

use crate::{mini_unicode::AllowedUnicodeRanges, parser::{BDFChar, BDFFont, BDFParser}};

const HEADER: &str = r#"// Generated by bdf2efifont.
#include <Protocol/HiiFont.h>
#include <Protocol/SimpleTextOut.h>

"#;

const BLOCK_DATA: &[u8] = include_bytes!("../contrib/unifont-blocks.bdf");

pub struct EFIFontNarrowGlyph {
	pub encoding: u16,
	pub attributes: u8,
	pub cell1: Vec<u8>,
}

pub struct EFIFontWideGlyph {
	pub encoding: u16,
	pub attributes: u8,
	pub cell1: Vec<u8>,
	pub cell2: Vec<u8>,
}

pub struct EFIGlyphData {
	pub narrow_glyphs: Vec<EFIFontNarrowGlyph>,
	pub wide_glyphs: Vec<EFIFontWideGlyph>,
}

#[derive(PartialEq, Eq)]
enum RenderingMode {
	Normal,
	BoxDrawing,
	Block,
}

fn render_bitmap(glyph: &BDFChar, mode: &RenderingMode) -> Result<Vec<Vec<u8>>> {
	// Rendered bitmap data
	let mut rendered = vec![];
	// The baseline offset (default is 3, assuming the characters are 16px high)
	let mut baseline = 3 + glyph.bb_offy;
	// Rows above 16px will be stripped.
	let mut strip_top = 0;
	// Rows below the 0px (with baseline offset) will be stripped.
	let mut strip_bottom = 0;

	if baseline < 0 {
		if glyph.bb_offy.unsigned_abs() < glyph.bb_y || glyph.bb_offy < -3 {
			// Now we can ignore some rows at the bottom
			strip_bottom = glyph.bb_offy.abs() - 3;
		}
		baseline = 0;
	}
	if glyph.bb_y > 16 {
		// Also strip some rows at the top
		strip_top = glyph.bb_y as i32 - 16;
	} else if glyph.bb_y > 19 {
		strip_top = (glyph.bb_y as i32 - 19) / 2;
		strip_bottom = glyph.bb_y as i32 - 19 - strip_top;
	} else if glyph.bb_y <= 16 && glyph.bb_y as i32 + baseline > 19 {
		baseline = 3;
	}

	// Chars without descender will be kept at the baseline.
	let actual_y = glyph.bb_y as i32 - strip_top - strip_bottom;
	let free_top = 19 - actual_y - baseline;
	let free_bottom = 19 - free_top - actual_y;
	if free_top < 0 {
		// We have a problem - the character still overflows.
		eprintln!("Glyph {0}/U+{0:4X} '{1}' still too tall after adjustments", glyph.encoding, glyph.charname);
		eprintln!("Metrics: height {}, baseline at {}px, top {} rows stripped, bottom {} rows stripped, top padding {} rows, bottom padding {} rows", glyph.bb_y, baseline, strip_top, strip_bottom, free_top, free_bottom);
		bail!("");
	}
	let mut iter = glyph.bitmap.iter();

	for i in 0..free_top {
		if *mode == RenderingMode::Normal {
			rendered.push(vec![0; glyph.bitmap[0].len()]);
		} else if *mode == RenderingMode::BoxDrawing {
			// Copy the top rows
			rendered.push(glyph.bitmap[0].clone());
		} else if *mode == RenderingMode::Block {
			// Copy the top even/odd rows
			rendered.push(glyph.bitmap[(i as usize + 1) % 2].clone());
		}
	}
	for _ in 0..strip_top {
		let _ = iter.next();
	}
	for _ in 0..actual_y {
		let row = if let Some(r) = iter.next() {
			r
		} else {
			bail!("Expecting more bitmap data");
		};

		// Copy bitmap data to EFI font data
		rendered.push(row.clone());
	}
	for i in 0..free_bottom {
		if *mode == RenderingMode::Normal {
			rendered.push(vec![0; glyph.bitmap[0].len()]);
		} else if *mode == RenderingMode::BoxDrawing {
			// Copy the bottom row
			rendered.push(glyph.bitmap.last().unwrap().clone());
		} else if *mode == RenderingMode::Block {
			// Copy the bottom even/odd rows
			rendered.push(glyph.bitmap[glyph.bb_y as usize - 1 - ((i as usize + 1) % 2)].clone());
		}
	}
	if rendered.len() != 19 {
		eprintln!("Metrics: height {}, baseline at {}px, top {} rows stripped, bottom {} rows stripped, top padding {} rows, bottom padding {} rows", glyph.bb_y, baseline, strip_top, strip_bottom, free_top, free_bottom);
		bail!("Expecting rendered glyphs that is exactly 19px in hight");
	}
	Ok(rendered)
}

pub fn convert(src: &BDFFont) -> Result<EFIGlyphData> {
	let mut narrow_glyphs = Vec::new();
	let mut wide_glyphs = Vec::new();
	let mut cursor = Cursor::new(BLOCK_DATA);
	eprintln!("Parsing block elements ...");
	let block_glyphs = BDFParser::parse(&mut cursor)?;
	for (desc, range) in AllowedUnicodeRanges::all_ranges() {
		eprintln!("Converting character range {}", desc.to_str());
		let (src, mode) = if *desc == AllowedUnicodeRanges::BoxDrawing {
				(&block_glyphs, RenderingMode::BoxDrawing)
			} else if *desc == AllowedUnicodeRanges::BlockElements {
				(&block_glyphs, RenderingMode::Block)
			} else {
				(src, RenderingMode::Normal)
		};
		for ch in range {
			let codepoint = ch as u64;
			if codepoint > 0xFFFF {
				bail!("Supplied range is out of range (EFI uses UCS-2, which limits the codepoint to from U+0000 to U+FFFF)");
			}
			let glyph = if let Some(g) = src.chars.get(&codepoint) {
				g
			} else {
				continue;
			};
			let encoding = codepoint as u16;
			let rows = render_bitmap(glyph, &mode).context(format!("Unable to render bitmap data for glyph {0}/U+{0:4X} '{1}'", glyph.encoding, glyph.charname))?;
			let cell1 = rows.iter().map(|c| c[0]).collect::<Vec<_>>();
			if glyph.bb_x <= 8 {
				let attributes = 0u8;
				narrow_glyphs.push(EFIFontNarrowGlyph { encoding, attributes, cell1 });
				// We're finished here.
				continue;
			}
			if glyph.bb_x <= 16 && [AllowedUnicodeRanges::CJKPunctuations, AllowedUnicodeRanges::CJKUnifiedIdeographs, AllowedUnicodeRanges::HalfAndFullWidthForms].contains(desc) {
				// Refer to MdePkg/Include/Uefi/UefiInternalFormRepresentation.h.
				let attributes = 2u8;
				let cell2 = rows.iter().map(|c| c[1]).collect::<Vec<_>>();
				wide_glyphs.push(EFIFontWideGlyph { encoding, attributes, cell1, cell2 });
				continue;
			}
			eprintln!("Warning: Glyph {} '{}' is too wide ({} cells) to be fit into the EFI font (2 cells), skipping.", glyph.encoding, glyph.charname, glyph.bb_x.div_ceil(8));
		}
	}

	Ok(EFIGlyphData { narrow_glyphs, wide_glyphs })
}

pub fn render<S, T, U>(src: &EFIGlyphData, name: S, output_prefix: T, symbol_prefix: U) -> Result<()>
where S: AsRef<str>, T: AsRef<str>, U: AsRef<str> {
	let output_prefix = output_prefix.as_ref();
	let output_narrow = format!("{}_narrow.c", output_prefix);
	let output_wide = format!("{}_wide.c", output_prefix);
	let out_fd = File::options().create(true).truncate(true).write(true).open(output_narrow)?;
	let mut bufwriter = BufWriter::with_capacity(1 << 14, out_fd);
	bufwriter.write_fmt(format_args!("// Font name: {}\n", name.as_ref()))?;
	bufwriter.write_fmt(format_args!("{}\n", HEADER))?;

	bufwriter.write_fmt(format_args!("EFI_NARROW_GLYPH {}NarrowGlyphData[] = {{\n", symbol_prefix.as_ref()))?;
	for glyph in &src.narrow_glyphs {
		bufwriter.write_fmt(format_args!("  {{ 0x{:04x} /* {} */, 0x{:04x}, {{ ", glyph.encoding, char::from_u32(glyph.encoding as u32).unwrap_or('?'), glyph.attributes))?;
		bufwriter.write_all(&glyph.cell1.iter().map(|b| format!("0x{:02x}", b)).collect::<Vec<_>>().join(", ").as_bytes())?;
		bufwriter.write_all(b" } },\n")?;
	}
	bufwriter.write_all(b"};\n")?;
	bufwriter.write_fmt(format_args!("UINT32 {0}NarrowGlyphSize = sizeof ({0}NarrowGlyphData);\n", symbol_prefix.as_ref()))?;
	bufwriter.flush()?;

	if src.wide_glyphs.is_empty() {
		return Ok(())
	}

	// Some copy pasta.
	let out_fd = File::options().create(true).truncate(true).write(true).open(output_wide)?;
	let mut bufwriter = BufWriter::with_capacity(1 << 14, out_fd);
	bufwriter.write_fmt(format_args!("// Font name: {}\n", name.as_ref()))?;
	bufwriter.write_fmt(format_args!("{}\n", HEADER))?;

	bufwriter.write_fmt(format_args!("EFI_WIDE_GLYPH {}WideGlyphData[] = {{\n", symbol_prefix.as_ref()))?;
	for glyph in &src.wide_glyphs {
		bufwriter.write_fmt(format_args!("  {{ 0x{:04x} /* {} */, 0x{:04x}, {{ ", glyph.encoding, char::from_u32(glyph.encoding as u32).unwrap_or('?'), glyph.attributes))?;
		bufwriter.write_all(&glyph.cell1.iter().map(|b| format!("0x{:02x}", b)).collect::<Vec<_>>().join(", ").as_bytes())?;
		bufwriter.write_all(b" }, { ")?;
		bufwriter.write_all(&glyph.cell2.iter().map(|b| format!("0x{:02x}", b)).collect::<Vec<_>>().join(", ").as_bytes())?;
		bufwriter.write_all(b" } },\n")?;
	}
	bufwriter.write_all(b"};\n")?;
	bufwriter.write_fmt(format_args!("UINT32 {0}WideGlyphSize = sizeof ({0}WideGlyphData);\n", symbol_prefix.as_ref()))?;
	bufwriter.flush()?;
	Ok(())
}
